#!/usr/bin/env node
// Stamp the current git SHA into both the app and the functions at build time,
// so the deployed backend can be compared against the deployed frontend. The
// failure this exists to catch: Pages auto-deploys the frontend, functions need
// a manual deploy, and nothing used to show that they had drifted apart.

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');

function gitSha() {
  try {
    return execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
}

/** The last commit that touched the functions: drift is measured against this, not HEAD, so a frontend-only commit never reads as a backend behind. */
function apiSha() {
  try {
    return execSync('git log -1 --format=%h -- api', { encoding: 'utf8', cwd: repoRoot }).trim() || 'unknown';
  } catch {
    return 'unknown';
  }
}

const sha = gitSha();
const api = apiSha();
const builtAt = new Date().toISOString();
const banner = '// Generated by scripts/gen-build-info.mjs — do not edit by hand.\n';
const body = `${banner}export const BUILD_SHA = '${sha}';
export const API_SHA = '${api}';
`;

for (const target of [
  resolve(repoRoot, 'frontend/src/app/build-info.ts'),
  resolve(repoRoot, 'api/src/build-info.ts')
]) {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, body, 'utf8');
}

// The same stamp as a static file the deployed site serves (12 Sep 2026).
//
// `verify` runs the moment `deploy` returns, but Pages propagates on its own
// clock, so the checks can run against the PREVIOUS build and pass — which is
// exactly what happened twice on 12 Sep, letting a broken check reach main. The
// backend already publishes its SHA and is compared against api/ history; the
// frontend stamped one too but only ever read it on the Admin page, which the
// read-only test account cannot open. A flat file anyone can GET closes that.
const publicDir = resolve(repoRoot, 'frontend/public');
mkdirSync(publicDir, { recursive: true });
writeFileSync(resolve(publicDir, 'build.json'), JSON.stringify({ sha, api, builtAt }, null, 2) + '\n', 'utf8');

console.log(`build-info: ${sha} (api ${api}) @ ${builtAt}`);
