/**
 * Build the champion → lane map from an Oracle's Elixir match export.
 *
 * Riot's own champion tags are classes, not lanes: Gragas is a Fighter whether
 * he is top, jungle or support, so a tag can never say where a pick belongs.
 * Pro match data can, because it records the position every champion was
 * actually played in.
 *
 * Oracle's Elixir publishes that export deliberately for analysts, which is why
 * it is the source here rather than a stats site — scraping one of those is
 * prohibited by Riot's General Policies and risks the API key.
 *
 * Usage:
 *   node scripts/gen-champion-lanes.mjs <path-to-oracles-elixir.csv>
 *
 * The CSV is far too big to commit (64 MB); the generated map is a few KB and
 * is, so a checkout needs no download to build.
 */

import { createReadStream, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline';
import { resolve } from 'node:path';

const OE_TO_ROLE = { top: 'Top', jng: 'Jungle', mid: 'Mid', bot: 'ADC', sup: 'Support' };
const ROLES = ['Top', 'Jungle', 'Mid', 'ADC', 'Support'];

/** Below this share of a champion's games, a lane is noise rather than a role. */
const MIN_SHARE = 0.08;

const csvPath = process.argv[2];
if (!csvPath) {
  console.error('Usage: node scripts/gen-champion-lanes.mjs <path-to-oracles-elixir.csv>');
  process.exit(1);
}

/** Split a CSV line, honouring quoted fields — champion names contain commas. */
function splitCsv(line) {
  const out = [];
  let cur = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      if (quoted && line[i + 1] === '"') { cur += '"'; i++; } else { quoted = !quoted; }
    } else if (ch === ',' && !quoted) {
      out.push(cur); cur = '';
    } else {
      cur += ch;
    }
  }
  out.push(cur);
  return out;
}

const counts = new Map();
let header = null;
let cols = {};
let rows = 0;

const rl = createInterface({ input: createReadStream(resolve(csvPath)), crlfDelay: Infinity });

for await (const line of rl) {
  if (!line.trim()) continue;
  const f = splitCsv(line);
  if (!header) {
    header = f;
    cols = {
      participantid: header.indexOf('participantid'),
      position: header.indexOf('position'),
      champion: header.indexOf('champion')
    };
    for (const [k, v] of Object.entries(cols)) {
      if (v < 0) { console.error(`Column "${k}" not found — is this an Oracle's Elixir export?`); process.exit(1); }
    }
    continue;
  }

  // participantid 1..10 are players; 100/200 are the team summary rows.
  const pid = Number(f[cols.participantid]);
  if (!Number.isFinite(pid) || pid > 10) continue;

  const role = OE_TO_ROLE[f[cols.position]];
  const champ = f[cols.champion]?.trim();
  if (!role || !champ) continue;

  if (!counts.has(champ)) counts.set(champ, { Top: 0, Jungle: 0, Mid: 0, ADC: 0, Support: 0 });
  counts.get(champ)[role] += 1;
  rows += 1;
}

/**
 * A champion's lanes, most-played first, keeping any that clear MIN_SHARE.
 * Several lanes are kept on purpose: a flex pick genuinely belongs in more than
 * one, and collapsing that to a single "real" lane is what makes an
 * auto-assignment feel wrong.
 */
const lanes = {};
for (const [champ, byRole] of [...counts].sort(([a], [b]) => a.localeCompare(b))) {
  const total = ROLES.reduce((sum, r) => sum + byRole[r], 0);
  if (!total) continue;
  const kept = ROLES
    .map((role) => ({ role, share: byRole[role] / total }))
    .filter((r) => r.share >= MIN_SHARE)
    .sort((a, b) => b.share - a.share);
  // A champion played almost entirely in one lane can fall below the threshold
  // in every other; never emit an empty list.
  lanes[champ] = (kept.length ? kept : [{ role: ROLES.reduce((best, r) => (byRole[r] > byRole[best] ? r : best), 'Mid'), share: 1 }])
    .map((r) => r.role);
}

const out = `// Generated by scripts/gen-champion-lanes.mjs — do not edit by hand.
//
// Which lanes each champion is actually played in, most common first, derived
// from Oracle's Elixir pro match data. Riot's champion tags are classes and
// cannot answer this: Gragas is a Fighter in all three of his lanes.
//
// Several lanes are kept where a champion genuinely flexes, so the draft can
// offer a choice rather than assert a wrong one.
import { Role } from '../models/team.models';

export const CHAMPION_LANES: Readonly<Record<string, readonly Role[]>> = ${JSON.stringify(lanes, null, 2)};
`;

const dest = resolve('frontend/src/app/data/champion-lanes.ts');
writeFileSync(dest, out);
console.log(`${Object.keys(lanes).length} champions from ${rows} player rows -> ${dest}`);
